import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
const [origin, destination, date] = process.argv.slice(2);
const transport = new StdioClientTransport({ command: "node", args: ["dist/index.js"], env: { ...process.env } as Record<string, string>, stderr: "inherit" });
const client = new Client({ name: "live-once", version: "0.0.0" });
await client.connect(transport);
const res = await client.callTool({ name: "awardfares_search", arguments: { origin: [origin], destination: [destination], dates: [date], live: true, maxWaitSeconds: 120 } }, undefined, { timeout: 300_000 });
console.log((res.content as Array<{ text?: string }>).map((c) => c.text).join("\n").slice(0, 2500));
await client.close();
process.exit(0);
